'use strict';
const { readFileSync, writeFileSync } = require('node:fs');
const { URL } = require('node:url');
const { retanguloDoCanvas } = require('./_canvas');

async function roteiro({ page, estado, afirmar, capturar }) {
  await page.goto(new URL('/?pausado&depuracao=militia,woodcutter,laborer', page.url()).href);
  await page.waitForFunction(() => window.__cangaco?.pronto);
  afirmar(true, 'cena de depuracao abriu');
  const carregar = async nome => {
    await page.evaluate(texto => window.localStorage.setItem('cangaco:partida', texto), readFileSync(`test-output/D-TELA-05c-${nome}.save.txt`, 'utf8'));
    await page.keyboard.press('h'); await page.click('#ajuda [data-acao="carregar"]'); await page.keyboard.press('Escape');
    await page.waitForTimeout(100);
  };
  const avancar = async n => { await page.evaluate(passos => window.__cangaco.avancar(passos), n); await page.waitForTimeout(100); };
  const centrar = async u => {
    const c = await retanguloDoCanvas(page);
    await page.evaluate(cam => window.__cangaco.fixarCamera(cam), { scrollX: u.gx * 64 - c.width / 2, scrollY: u.gy * 64 - c.height / 2 });
    await page.waitForTimeout(100);
  };
  const quadros = [];
  await carregar('morte');
  const loaded = await estado();
  afirmar(loaded.unidadesRenderizadas.some(u => u.id === 'faminto'), 'save da fome carregado');
  await centrar((await estado()).unidadesRenderizadas.find(u => u.id === 'faminto'));
  await page.waitForFunction(() => window.__cangaco.unidadesRenderizadas.find(u => u.id === 'faminto')?.frame);
  await avancar(1);
  let s = await estado();
  afirmar(!s.unidadesRenderizadas.some(u => u.id === 'faminto'), 'morte logica ja removeu militar');
  afirmar(s.mortesRenderizadas[0]?.quadro === 0 && s.corposNaMemoria === 1, 'corpo inicia no quadro zero separado da lista viva');
  await capturar('morte-queda'); quadros.push(s.mortesRenderizadas[0]);
  await page.waitForTimeout(150);
  afirmar((await estado()).mortesRenderizadas[0]?.quadro === 0, 'pausa congela corpo');
  await avancar(2); s = await estado();
  afirmar(s.mortesRenderizadas[0]?.quadro === 2, 'esqueleto no terceiro quadro');
  afirmar(s.mortesRenderizadas[0]?.peY === 0, 'pe do recorte de morte permanece constante');
  await capturar('esqueleto'); quadros.push(s.mortesRenderizadas[0]);
  await avancar(2); s = await estado();
  afirmar(s.mortesRenderizadas[0]?.quadro === 4, 'dissipacao no quinto quadro');
  await capturar('desaparecimento'); quadros.push(s.mortesRenderizadas[0]);
  await avancar(2);
  afirmar((await estado()).corposNaMemoria === 0, 'fim da sequencia libera corpo');
  await carregar('morte'); await avancar(1);
  afirmar((await estado()).corposNaMemoria === 1, 'nova morte cria um corpo');
  const tickAntesDoLoad = (await estado()).tick;
  await carregar('morte-mesmo-tick');
  afirmar((await estado()).tick === tickAntesDoLoad, 'load preserva o mesmo tick da partida anterior');
  afirmar((await estado()).corposNaMemoria === 0, 'load limpa corpo no mesmo tick e com os mesmos ids');
  await carregar('ataque');
  await centrar((await estado()).unidadesRenderizadas.find(u => u.id === 'atacante'));
  await avancar(1);
  s = await estado();
  const atacante = s.unidadesRenderizadas.find(u => u.id === 'atacante');
  afirmar(atacante?.animacao === 'atacar' && atacante.quadro === 0, 'ataque real inicia no quadro zero');
  afirmar(atacante.direcao === atacante.direcaoLogica, 'golpe olha na direcao logica sem virada intermediaria');
  await capturar('ataque-real');
  const acoes = [atacante];
  await page.keyboard.press('p'); await page.waitForTimeout(150); await page.keyboard.press('p');
  await carregar('lenhador');
  await centrar((await estado()).unidadesRenderizadas.find(u => u.id === 'lenhador-1'));
  await page.waitForFunction(() => window.__cangaco.unidadesRenderizadas.find(u => u.id === 'lenhador-1')?.animacao === 'trabalhar');
  s = await estado();
  const lenhador = s.unidadesRenderizadas.find(u => u.id === 'lenhador-1');
  afirmar(lenhador.quadro === 0 && lenhador.fsm === 'colhendo', 'colheita real inicia trabalho no quadro zero');
  acoes.push(lenhador); await capturar('lenhador-colhendo');
  await avancar(2); s = await estado();
  afirmar(s.unidadesRenderizadas.find(u => u.id === 'lenhador-1').quadro === 2, 'trabalho avanca pelo tempo desde entrada');
  await carregar('laborer');
  let laborer = (await estado()).unidadesRenderizadas.find(u => ['nivelando', 'martelando'].includes(u.fsm));
  await centrar(laborer);
  await page.waitForFunction(() => window.__cangaco.unidadesRenderizadas.some(u => u.tipo === 'laborer' && u.animacao === 'trabalhar'));
  laborer = (await estado()).unidadesRenderizadas.find(u => u.tipo === 'laborer' && u.animacao === 'trabalhar');
  afirmar(laborer.quadro === 0, 'construcao real inicia trabalho no quadro zero');
  acoes.push(laborer); await capturar('laborer-na-obra');
  writeFileSync('test-output/D-TELA-05c-roteiro.json', JSON.stringify({ quadros, acoes, memoriaFinal: (await estado()).corposNaMemoria }, null, 2));
}
module.exports = { roteiro };
